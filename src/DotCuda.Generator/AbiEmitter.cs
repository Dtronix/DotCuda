using System.Text;

namespace DotCuda.Generator;

/// <summary>
/// Writes abi_&lt;lib&gt;.c (prints sizeof/offsetof/enum/constant values as JSON lines when compiled by a C compiler)
/// and AbiExpected.&lt;Lib&gt;.g.cs (the same keys, with clang's numbers and the C# layout measured at run time).
/// Keys: size:Type[.field...], off:Type.field[.field...], enum:Enum.Member, const:Class.Name.
/// </summary>
sealed class AbiEmitter(LibraryModel model, string outDir)
{
    readonly LibraryConfig _cfg = model.Config;
    readonly StringBuilder _c = new();
    readonly StringBuilder _cs = new();
    readonly List<string> _methods = [];

    public void Emit()
    {
        Directory.CreateDirectory(outDir);
        _c.AppendLine($"/* Generated by DotCuda.Generator from {_cfg.Header}. Do not edit. */");
        _c.AppendLine("#include <stdio.h>");
        _c.AppendLine("#include <stddef.h>");
        if (_cfg.PerThreadDefaultStream) _c.AppendLine("#define CUDA_API_PER_THREAD_DEFAULT_STREAM 1");
        foreach (var d in _cfg.Defines) _c.AppendLine($"#define {d.Replace("=", " ")}");
        _c.AppendLine($"#include \"{_cfg.Header}\"");
        foreach (var extra in _cfg.ExtraIncludes) _c.AppendLine($"#include \"{extra}\"");
        _c.AppendLine();
        _c.AppendLine("static void P(const char* k, long long v) { printf(\"{\\\"k\\\":\\\"%s\\\",\\\"v\\\":%lld}\\n\", k, v); }");
        _c.AppendLine();
        _c.AppendLine("int main(void)");
        _c.AppendLine("{");

        foreach (var s in model.Emitted<StructItem>()) Struct(s);
        Enums();
        Constants();

        _c.AppendLine("    return 0;");
        _c.AppendLine("}");
        File.WriteAllText(Path.Combine(outDir, $"abi_{_cfg.Name.ToLowerInvariant()}.c"), _c.ToString());
        // Include directories beyond %CUDA_PATH%\include (e.g. the cuDNN SDK), as configured: resolved again by the test.
        File.WriteAllLines(Path.Combine(outDir, $"abi_{_cfg.Name.ToLowerInvariant()}.includes"), _cfg.IncludeDirs);

        var cs = new StringBuilder();
        cs.AppendLine("// <auto-generated>");
        cs.AppendLine($"//   Generated by DotCuda.Generator from {_cfg.Header}. Do not edit.");
        cs.AppendLine("// </auto-generated>");
        cs.AppendLine("#pragma warning disable CS0612, CS0618");
        cs.AppendLine($"using {_cfg.Namespace};");
        cs.AppendLine();
        cs.AppendLine("namespace DotCuda.AbiTests;");
        cs.AppendLine();
        cs.AppendLine("static unsafe partial class AbiExpected");
        cs.AppendLine("{");
        cs.AppendLine($"    public const string {_cfg.Name}Header = \"{_cfg.Header}\";");
        cs.AppendLine();
        cs.AppendLine($"    public static void Collect{_cfg.Name}(List<AbiFact> f)");
        cs.AppendLine("    {");
        foreach (var m in _methods) cs.AppendLine($"        {m}(f);");
        cs.AppendLine("    }");
        cs.Append(_cs);
        cs.AppendLine("}");
        File.WriteAllText(Path.Combine(outDir, $"AbiExpected.{_cfg.Name}.g.cs"), cs.ToString());
    }

    StringBuilder Method(string suffix)
    {
        var name = $"{_cfg.Name}_{suffix}";
        _methods.Add(name);
        _cs.AppendLine();
        _cs.AppendLine($"    static void {name}(List<AbiFact> f)");
        _cs.AppendLine("    {");
        return _cs;
    }

    void Struct(StructItem s)
    {
        var cs = Method(s.CsName);
        cs.AppendLine($"        {s.CsName} s = default;");
        cs.AppendLine("        byte* b = (byte*)&s;");
        Record(s, cs, csTypePath: s.CsName, keyPath: s.CsName, csAccess: "s", cAccess: "", baseOffset: 0, cTop: s.CSpelling!, cSizeExpr: $"sizeof({s.CSpelling})");
        cs.AppendLine("    }");
    }

    /// <param name="cAccess">C member path from the top-level type ("" at top, null when unreachable through an anonymous member).</param>
    void Record(StructItem s, StringBuilder cs, string csTypePath, string keyPath, string csAccess, string? cAccess, long baseOffset, string cTop, string? cSizeExpr)
    {
        var sizeKey = $"size:{keyPath}";
        cs.AppendLine($"        f.Add(new(\"{sizeKey}\", sizeof({csTypePath}), {s.Size}));");
        if (cSizeExpr is not null) _c.AppendLine($"    P(\"{sizeKey}\", (long long){cSizeExpr});");

        foreach (var fld in s.Fields)
        {
            var name = fld.CsName.TrimStart('@');
            var fieldKey = $"{keyPath}.{name}";
            var abs = baseOffset + fld.Offset;
            cs.AppendLine($"        f.Add(new(\"off:{fieldKey}\", (byte*)&{csAccess}.{fld.CsName} - b, {abs}));");
            // C reaches members of an anonymous member directly, so the anonymous level adds nothing to the path.
            string? cPath = fld.CName is null ? cAccess : cAccess is null ? null : (cAccess.Length == 0 ? fld.CName : $"{cAccess}.{fld.CName}");
            if (fld.CName is not null && cPath is not null)
                _c.AppendLine($"    P(\"off:{fieldKey}\", (long long)offsetof({cTop}, {cPath}));");
            else if (fld.CName is null && cAccess is not null && fld.NestedType?.Fields.FirstOrDefault()?.CName is { } first)
                // An anonymous member has no name in C, but a struct/union never has leading padding, so its offset is its first field's.
                _c.AppendLine($"    P(\"off:{fieldKey}\", (long long)offsetof({cTop}, {(cAccess.Length == 0 ? first : $"{cAccess}.{first}")}));");
            if (fld.NestedType is { } n)
            {
                // For an array of anonymous records, check element 0 (its offset equals the array's).
                var idx = fld.NestedIsArrayElement ? "[0]" : "";
                var nestedCPath = fld.CName is null ? cAccess : cPath is null ? null : cPath + idx;
                string? nestedSize = fld.CName is not null && cPath is not null ? $"sizeof((({cTop}*)0)->{nestedCPath})" : null;
                Record(n, cs, $"{csTypePath}.{n.CsName}", fieldKey + idx, $"{csAccess}.{fld.CsName}{idx}",
                    nestedCPath, abs, cTop, nestedSize);
            }
        }
    }

    void Enums()
    {
        foreach (var e in model.Emitted<EnumItem>())
        {
            var cs = Method(e.CsName);
            foreach (var m in e.Members)
            {
                var key = $"enum:{e.CsName}.{m.Name.TrimStart('@')}";
                cs.AppendLine($"        f.Add(new(\"{key}\", unchecked((long){e.CsName}.{m.Name}), {m.RawValue}));");
                _c.AppendLine($"    P(\"{key}\", (long long){m.Name.TrimStart('@')});");
            }
            cs.AppendLine("    }");
        }
    }

    void Constants()
    {
        var constants = model.Emitted<ConstantItem>().Where(c => c.RawValue is not null).ToList();
        if (constants.Count == 0) return;
        var cs = Method("Constants");
        foreach (var c in constants)
        {
            var key = $"const:{_cfg.ClassName}.{c.CsName}";
            var cls = $"global::{_cfg.Namespace}.{_cfg.ClassName}";
            var value = c.StaticReadonly ? $"{cls}.{c.CsName}.Value" : $"{cls}.{c.CsName}";
            cs.AppendLine($"        f.Add(new(\"{key}\", unchecked((long){value}), {c.RawValue}));");
            _c.AppendLine($"    P(\"{key}\", (long long)({c.CsName}));");
        }
        cs.AppendLine("    }");
    }
}
