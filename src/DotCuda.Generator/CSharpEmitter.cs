using System.Security;
using System.Text;

namespace DotCuda.Generator;

/// <summary>Writes a library's Generated/*.g.cs, Package.g.props and SKIPPED.md.</summary>
sealed class CSharpEmitter(LibraryModel model, string outDir, IReadOnlyList<string> referencedNamespaces)
{
    readonly LibraryConfig _cfg = model.Config;

    public void Emit()
    {
        Directory.CreateDirectory(outDir);
        foreach (var stale in Directory.GetFiles(outDir, "*.g.cs")) File.Delete(stale);
        Write("Functions.g.cs", Functions());
        Write("Enums.g.cs", Enums());
        Write("Structs.g.cs", Structs());
        Write("Handles.g.cs", Handles());
        Write("Constants.g.cs", Constants());
        Write("LibraryNames.g.cs", LibraryNames());
        File.WriteAllText(Path.Combine(outDir, "Package.g.props"), PackageProps());
        File.WriteAllText(Path.Combine(outDir, "SKIPPED.md"), SkippedMarkdown());
    }

    void Write(string file, string body) => File.WriteAllText(Path.Combine(outDir, file), Banner() + body);

    string Banner()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine($"//   Generated by DotCuda.Generator from {_cfg.Header} ({Path.GetFileName(_cfg.ConfigPath)}). Do not edit.");
        sb.AppendLine($"//   Headers: CUDA {model.CudaVersion}" + string.Concat(model.VersionInfo.Where(kv => kv.Key != "CUDA_VERSION").Select(kv => $", {kv.Key}={kv.Value}")) + ".");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#pragma warning disable CS0612, CS0618 // deprecated CUDA declarations refer to each other");
        sb.AppendLine();
        return sb.ToString();
    }

    // ---------------------------------------------------------------- files

    string Functions()
    {
        var sb = Begin("System.Runtime.InteropServices");
        sb.AppendLine($"public static unsafe partial class {_cfg.ClassName}");
        sb.AppendLine("{");
        bool first = true;
        foreach (var f in model.Emitted<FunctionItem>())
        {
            if (!first) sb.AppendLine();
            first = false;
            Doc(sb, f.Doc, "    ");
            Obsolete(sb, f.Obsolete, "    ");
            var entry = f.EntryPoint == f.CsName ? "" : $", EntryPoint = \"{f.EntryPoint}\"";
            sb.AppendLine($"    [LibraryImport(LibraryName{entry})]");
            var ps = string.Join(", ", f.Parameters.Select(p => $"{p.Type} {p.Name}"));
            sb.AppendLine($"    public static partial {f.ReturnType} {f.CsName}({ps});");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    string Enums()
    {
        var sb = Begin();
        foreach (var e in model.Emitted<EnumItem>())
        {
            Doc(sb, e.Doc, "", $"<c>{e.CSpelling}</c>");
            Obsolete(sb, e.Obsolete, "");
            sb.AppendLine($"public enum {e.CsName} : {e.Underlying}");
            sb.AppendLine("{");
            foreach (var m in e.Members)
            {
                Doc(sb, m.Doc, "    ");
                Obsolete(sb, m.Obsolete, "    ");
                sb.AppendLine($"    {m.Name} = {m.Value},");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }
        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    string Structs()
    {
        var sb = Begin("System.Runtime.CompilerServices", "System.Runtime.InteropServices");
        foreach (var s in model.Emitted<StructItem>())
        {
            Struct(sb, s, "", $"<c>{s.CSpelling}</c>, {s.Size} bytes");
            sb.AppendLine();
        }
        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    void Struct(StringBuilder sb, StructItem s, string indent, string? summarySuffix)
    {
        Doc(sb, s.Doc, indent, summarySuffix);
        Obsolete(sb, s.Obsolete, indent);
        sb.AppendLine($"{indent}[StructLayout(LayoutKind.{(s.IsUnion ? "Explicit" : "Sequential")})]");
        sb.AppendLine($"{indent}public unsafe partial struct {s.CsName}");
        sb.AppendLine($"{indent}{{");
        var inner = indent + "    ";
        foreach (var f in s.Fields)
        {
            Doc(sb, f.Doc, inner);
            if (s.IsUnion) sb.AppendLine($"{inner}[FieldOffset({f.Offset})]");
            sb.AppendLine($"{inner}public {f.CsType} {f.CsName};");
        }
        foreach (var n in s.Nested)
        {
            sb.AppendLine();
            Struct(sb, n, inner, null);
        }
        foreach (var b in s.Buffers)
        {
            sb.AppendLine();
            if (b.Comment is not null) sb.AppendLine($"{inner}/// <summary>Elements are <c>{SecurityElement.Escape(b.Comment)}</c>.</summary>");
            sb.AppendLine($"{inner}[InlineArray({b.Length})]");
            sb.AppendLine($"{inner}public struct {b.Name} {{ private {b.ElementType} _e0; }}");
        }
        sb.AppendLine($"{indent}}}");
    }

    string Handles()
    {
        var sb = Begin();
        foreach (var h in model.Emitted<HandleItem>())
        {
            var what = h.ValueType == "nint" ? "Opaque handle" : "Integer handle";
            sb.AppendLine($"/// <summary>{what}: <c>{SecurityElement.Escape(h.CDescription)}</c>.</summary>");
            sb.AppendLine($"public readonly partial record struct {h.CsName}({h.ValueType} Value);");
            sb.AppendLine();
        }
        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    string Constants()
    {
        var sb = Begin();
        sb.AppendLine($"public static unsafe partial class {_cfg.ClassName}");
        sb.AppendLine("{");
        foreach (var c in model.Emitted<ConstantItem>())
        {
            if (c.Doc is not null) sb.AppendLine($"    /// <summary>{c.Doc}</summary>");
            var kind = c.StaticReadonly ? "static readonly" : "const";
            sb.AppendLine($"    public {kind} {c.CsType} {c.CsName} = {c.Value};");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    string LibraryNames()
    {
        var lib = _cfg.Library;
        static string Arr(List<string> xs) => xs.Count == 0 ? "[]" : "[" + string.Join(", ", xs.Select(x => $"\"{x}\"")) + "]";
        var sb = new StringBuilder();
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine();
        sb.AppendLine("[assembly: DisableRuntimeMarshalling]");
        sb.AppendLine();
        sb.AppendLine($"namespace {_cfg.Namespace};");
        sb.AppendLine();
        sb.AppendLine($"public static unsafe partial class {_cfg.ClassName}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Logical library name used by every binding in this class; resolved by <see cref=\"DotCuda.NativeLibraries\"/>.</summary>");
        sb.AppendLine($"    public const string LibraryName = \"{lib.LogicalName}\";");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Version of the headers these bindings were generated from (also the package version).</summary>");
        sb.AppendLine($"    public const string HeaderVersion = \"{model.HeaderVersion}\";");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Per-platform file names for <see cref=\"LibraryName\"/>.</summary>");
        sb.AppendLine($"    public static readonly DotCuda.NativeLibrarySpec Library = new(LibraryName,");
        sb.AppendLine($"        WindowsFile: \"{lib.Windows}\", LinuxFile: \"{lib.Linux}\",");
        sb.AppendLine($"        WindowsPreload: {Arr(lib.WindowsPreload)}, LinuxPreload: {Arr(lib.LinuxPreload)},");
        sb.AppendLine($"        UseLibDir: {(lib.UseLibDir ? "true" : "false")});");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"internal static class {_cfg.ClassName}ModuleInitializer");
        sb.AppendLine("{");
        sb.AppendLine("#pragma warning disable CA2255 // the resolver must be registered before any [LibraryImport] stub runs");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("#pragma warning restore CA2255");
        sb.AppendLine($"    internal static void Init() => DotCuda.NativeLibraries.Register(typeof({_cfg.ClassName}).Assembly, {_cfg.ClassName}.Library);");
        sb.AppendLine("}");
        return sb.ToString();
    }

    string PackageProps() => $"""
        <!-- Generated by DotCuda.Generator. Do not edit. -->
        <Project>
          <PropertyGroup>
            <!-- Version of the headers the bindings were generated from; the package version is the project's. -->
            <DotCudaHeaderVersion>{model.HeaderVersion}</DotCudaHeaderVersion>
          </PropertyGroup>
        </Project>

        """;

    string SkippedMarkdown()
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# Skipped declarations: {_cfg.Name}");
        sb.AppendLine();
        sb.AppendLine($"Generated from `{_cfg.Header}` (CUDA {model.HeaderVersion}). Every declaration in the library's headers that has no binding, and why.");
        sb.AppendLine();
        sb.AppendLine("| Counts | |");
        sb.AppendLine("| --- | --- |");
        sb.AppendLine($"| Functions | {model.Emitted<FunctionItem>().Count()} |");
        sb.AppendLine($"| Enums | {model.Emitted<EnumItem>().Count()} |");
        sb.AppendLine($"| Structs / unions | {model.Emitted<StructItem>().Count()} |");
        sb.AppendLine($"| Handles | {model.Emitted<HandleItem>().Count()} |");
        sb.AppendLine($"| Constants | {model.Emitted<ConstantItem>().Count()} |");
        sb.AppendLine($"| **Skipped** | **{model.Skipped.Count}** |");
        sb.AppendLine();
        if (model.Skipped.Count == 0)
        {
            sb.AppendLine("Nothing was skipped.");
            return sb.ToString();
        }
        sb.AppendLine("| Kind | Name | File | Reason |");
        sb.AppendLine("| --- | --- | --- | --- |");
        foreach (var s in model.Skipped.OrderBy(s => s.Kind).ThenBy(s => s.Name, StringComparer.Ordinal))
            sb.AppendLine($"| {s.Kind} | `{s.Name}` | {Path.GetFileName(s.File)} | {s.Reason.Replace("|", "\\|")} |");
        return sb.ToString();
    }

    // ---------------------------------------------------------------- helpers

    StringBuilder Begin(params string[] usings)
    {
        var sb = new StringBuilder();
        var all = usings.Concat(referencedNamespaces.Where(n => n != _cfg.Namespace)).Distinct().ToList();
        foreach (var u in all) sb.AppendLine($"using {u};");
        if (all.Count > 0) sb.AppendLine();
        sb.AppendLine($"namespace {_cfg.Namespace};");
        sb.AppendLine();
        return sb;
    }

    static void Doc(StringBuilder sb, string? doc, string indent, string? suffix = null)
    {
        if (doc is null && suffix is null) return;
        var text = doc is null ? "" : SecurityElement.Escape(string.Join(' ', doc.Split((char[])['\r', '\n'], StringSplitOptions.RemoveEmptyEntries).Select(l => l.Trim())));
        if (suffix is not null) text = text.Length == 0 ? suffix : $"{text} ({suffix})";
        sb.AppendLine($"{indent}/// <summary>{text}</summary>");
    }

    static void Obsolete(StringBuilder sb, string? message, string indent)
    {
        if (message is not null) sb.AppendLine($"{indent}[System.Obsolete(\"{message.Replace("\"", "\\\"")}\")]");
    }
}
